import * as github from "@actions/github";
import type { PullRequestSnapshot } from "./pull-request.js";
import type { ReviewResult } from "../review/types.js";
import { createFindingKey, resolveOutdatedMergePilotThreads } from "./review-thread-manager.js";

type Octokit = ReturnType<typeof github.getOctokit>;

const MAX_INLINE_COMMENTS = 50;
const SUMMARY_MARKER = "<!-- mergepilot-summary -->";

export interface PublishReviewOptions {
  owner: string;
  repo: string;
  pullNumber: number;
  commitSha: string;
}

function formatFinding(finding: ReviewResult["findings"][number]): string {
  const lines = [
    `**[${finding.severity.toUpperCase()}] ${finding.title}**`,
    finding.description,
  ];
  if (finding.suggestion) lines.push(`**Suggestion:** ${finding.suggestion}`);
  lines.push(`_Confidence: ${Math.round(finding.confidence * 100)}%_`);
  lines.push(`<!-- mergepilot-finding:${createFindingKey(finding)} -->`);
  return lines.join("\n\n");
}

function formatOverflowFinding(finding: ReviewResult["findings"][number]): string {
  const lines = [
    `- **[${finding.severity.toUpperCase()}] ${finding.filePath}:${finding.line} — ${finding.title}**`,
    `  ${finding.description.replace(/\s+/g, " ").trim()}`,
  ];
  if (finding.suggestion) lines.push(`  Suggestion: ${finding.suggestion.replace(/\s+/g, " ").trim()}`);
  return lines.join("\n");
}

export async function publishReview(
  octokit: Octokit,
  pullRequest: PullRequestSnapshot,
  result: ReviewResult,
  options: PublishReviewOptions,
): Promise<void> {
  const reviewMarker = `<!-- mergepilot-review:${options.commitSha} -->`;
  const existingReviews = await octokit.paginate(octokit.rest.pulls.listReviews, {
    owner: options.owner,
    repo: options.repo,
    pull_number: options.pullNumber,
    per_page: 100,
  });
  const existingSummaryComments = await octokit.paginate(octokit.rest.issues.listComments, {
    owner: options.owner,
    repo: options.repo,
    issue_number: options.pullNumber,
    per_page: 100,
  });

  const availableFiles = new Set(
    pullRequest.files
      .filter((file) => file.patch !== undefined && file.status !== "removed")
      .map((file) => file.filename),
  );

  const findings = result.findings.filter((finding) =>
    availableFiles.has(finding.filePath)
  );
  const inlineFindings = findings.slice(0, MAX_INLINE_COMMENTS);
  const overflowFindings = findings.slice(MAX_INLINE_COMMENTS);
  const comments = inlineFindings.map((finding) => ({
    path: finding.filePath,
    line: finding.line,
    side: "RIGHT" as const,
    body: formatFinding(finding),
  }));

  const findingLabel = findings.length === 1 ? "finding" : "findings";
  const summaryLines = [
    "## 🤖 MergePilot — Code Review",
    "",
    "> Automated code review",
    "",
    "### Summary",
    result.summary || "The review completed without a summary.",
    "",
    "### Review results",
    `**${findings.length} validated ${findingLabel}**`,
    "",
    findings.length === 0
      ? "No actionable issues were identified in the reviewed changes."
      : "See the inline comments for details and suggested improvements.",
    "",
    "---",
    "> **Advisory review:** AI-generated findings may be incomplete or incorrect. Please verify each finding before making changes.",
    "",
    "<sub>Generated by MergePilot · Automated Pull Request Reviewer</sub>",
  ];

  if (overflowFindings.length > 0) {
    summaryLines.push(
      "",
      `### Additional findings (${overflowFindings.length}; no inline comment due to GitHub's 50-comment limit)`,
      ...overflowFindings.map(formatOverflowFinding),
    );
  }
  summaryLines.push("", SUMMARY_MARKER);

  const summaryBody = summaryLines.join("\n");
  const existingSummary = existingSummaryComments.find((comment) =>
    comment.user?.type === "Bot" && comment.body?.includes(SUMMARY_MARKER)
  );

  if (existingSummary) {
    await octokit.rest.issues.updateComment({
      owner: options.owner,
      repo: options.repo,
      comment_id: existingSummary.id,
      body: summaryBody,
    });
  } else {
    await octokit.rest.issues.createComment({
      owner: options.owner,
      repo: options.repo,
      issue_number: options.pullNumber,
      body: summaryBody,
    });
  }

  if (existingReviews.some((review) =>
    review.commit_id === options.commitSha && review.body?.includes(reviewMarker)
  )) {
    return;
  }

  await resolveOutdatedMergePilotThreads(
    octokit, options.owner, options.repo, options.pullNumber, inlineFindings,
  );

  await octokit.rest.pulls.createReview({
    owner: options.owner,
    repo: options.repo,
    pull_number: options.pullNumber,
    commit_id: options.commitSha,
    event: "COMMENT",
    body: reviewMarker,
    comments,
  });
}
